"""Recommendation schema definitions matching Hackathon and prototype specifications."""

from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field
from backend.app.schemas.prediction_schema import (
    FeedPredictionResult,
    WastePredictionResult,
    PollutionRiskResult,
)


class MealScheduleItem(BaseModel):
    """An individual scheduled feeding event."""

    meal_number: int = Field(..., description="1-indexed meal sequence")
    time: str = Field(..., description="Clock time for feeding, e.g. '08:00 AM'")
    quantity_kg: float = Field(..., description="Feed quantity for this meal in kilograms")


class BaselineComparison(BaseModel):
    """Comparison between traditional static feeding and AquaNex AI optimized feeding."""

    baseline_feed_kg: float = Field(..., description="Static stage-based daily feed (kg)")
    baseline_waste_kg: float = Field(..., description="Estimated waste without adaptive optimization (kg)")
    baseline_daily_cost: float = Field(..., description="Daily feed expenditure at baseline (USD)")
    baseline_pollution_risk: str = Field(..., description="Pollution risk tier under baseline feeding")
    baseline_waste_risk_score: int = Field(..., description="Baseline waste risk score (0-100)")
    baseline_pollution_risk_score: int = Field(..., description="Baseline pollution risk score (0-100)")
    feed_saved_kg: float = Field(..., description="Daily feed saved by optimization (kg)")
    waste_prevented_kg: float = Field(..., description="Uneaten feed waste prevented (kg)")
    cost_saved_usd: float = Field(..., description="Net daily operational cost savings (USD)")


class OptimizationResult(BaseModel):
    """SciPy constrained optimization output and feeding schedule."""

    optimized_daily_feed_kg: float = Field(..., description="Total optimized feed for the day (kg)")
    number_of_meals: int = Field(..., description="Selected number of feeding events")
    meal_schedule: List[MealScheduleItem] = Field(..., description="Dispersed meal times and rations")
    feed_per_meal_kg: float = Field(..., description="Ration per meal in kg")
    estimated_daily_cost: float = Field(..., description="Estimated cost of optimized daily feed (USD)")
    solver_status: str = Field(default="converged", description="SciPy optimizer termination status")
    baseline_comparison: Optional[BaselineComparison] = Field(
        default=None,
        description="Head-to-head comparison with unoptimized feeding",
    )


class FeatureContribution(BaseModel):
    """SHAP feature contribution details."""

    feature: str = Field(..., description="Feature name")
    display_name: str = Field(..., description="Human-readable feature title")
    value: Any = Field(..., description="Observed input value")
    shap_value: float = Field(..., description="SHAP attribution magnitude and sign")
    impact_direction: str = Field(..., description="'INCREASES FEED' or 'DECREASES FEED'")


class ExplanationResult(BaseModel):
    """SHAP explainable AI insights explaining why the model produced this recommendation."""

    top_features: List[FeatureContribution] = Field(
        default_factory=list,
        description="Top influential features ranked by absolute SHAP attribution",
    )
    summary: str = Field(..., description="Plain-language diagnostic summary of model drivers")
    bullet_points: List[str] = Field(
        default_factory=list,
        description="Contextual explanations for farm operators",
    )


class FinalRecommendationResponse(BaseModel):
    """Central response object generated by recommendation_service.py."""

    pond_id: str = Field(default="pond_01")
    feed_prediction: FeedPredictionResult
    waste_prediction: WastePredictionResult
    pollution_risk: PollutionRiskResult
    optimization: OptimizationResult
    explanation: ExplanationResult
    warnings: List[str] = Field(default_factory=list)
    outside_validated_range: bool = Field(default=False)
    reliability: str = Field(default="Prediction reliability: Model-based estimate")
    dataset_disclaimer: str = Field(
        default="Controlled simulated prototype dataset — developed for Aarambh WCE Hackathon 2026."
    )
    frontend_feeding_result: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Adapted structure directly consumable by the Next.js dashboard UI",
    )
